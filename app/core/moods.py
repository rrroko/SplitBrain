
from typing import Tuple

# 感情 → (おすすめモード, 一言)
MOOD_MAP = {
    "元気": ("集中", "調子よさそうなので集中モードをおすすめします"),
    "普通": ("集中", "このまま集中モードで進められます"),
    "疲れた": ("リラックス", "少し休憩してから再開しましょう"),
    "眠い": ("リラックス", "音楽や明るさを落としてリラックスします"),
    "緊張": ("プレゼン", "発表に向けた表示にします"),
}

def suggest_mode(mood: str) -> Tuple[str, str]:
    """感情からおすすめモードとメッセージを返す"""
    return MOOD_MAP.get(mood, ("集中", "デフォルトで集中モードにします"))
